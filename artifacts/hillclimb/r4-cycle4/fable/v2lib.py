def vertex_int_exponents(v):
    """(D, lamD, muD) with integer exponents over the common denominator D."""
    D = 1
    for q in v:
        D = D * q.denominator // math.gcd(D, q.denominator)
    k = len(v) // 2
    return D, [int(q * D) for q in v[:k]], [int(q * D) for q in v[k:]]


def mono_powD(r, s, lamD, muD):
    val = F(1)
    for e in range(len(r)):
        if lamD[e]:
            val *= F(r[e]) ** lamD[e]
        if muD[e]:
            val *= F(s[e]) ** muD[e]
    return val


def certify_instance(mats, vinfo, bits=60):
    """For each vertex (D, lamD, muD): 'ok' (Out^D <= mono(s_lo)^D), 'VIOLATION' (Out^D > mono(s_hi)^D), or
    'undecided'.  Returns (out, r, s_lo, s_hi, list of statuses)."""
    out = out4(*mats)
    r, s_lo, s_hi = stats_brackets(mats, bits)
    statuses = []
    for (D, lamD, muD) in vinfo:
        if out == 0:
            statuses.append('ok')
            continue
        oD = F(out) ** D
        if oD <= mono_powD(r, s_lo, lamD, muD):
            statuses.append('ok')
        elif oD > mono_powD(r, s_hi, lamD, muD):
            statuses.append('VIOLATION')
        else:
            statuses.append('undecided')
    return out, r, s_lo, s_hi, statuses


