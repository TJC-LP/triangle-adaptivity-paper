"""Independent exact-arithmetic library for the labelled 4-cycle verification (v2-cyc4-fable).

Written from scratch; nothing is imported from the solver's or the other verifier's directories.
Everything load-bearing is in integers / fractions.Fraction.

Conventions: cycle vertices 0=X, 1=Y, 2=Z, 3=W; edges e: 0=R=(X,Y), 1=S=(Y,Z), 2=T=(Z,W), 3=Q=(W,X).
Instance = (AR, AS, AT, AQ), 0/1 matrices as lists of lists; AR is X x Y, AS is Y x Z, AT is Z x W, AQ is W x X.
Out = tr(AR AS AT AQ).
"""
from fractions import Fraction
import itertools
import math

F = Fraction
NAMES = ["R", "S", "T", "Q"]


# ----------------------------------------------------------------------------------------------
# arcs / edges / dual polyhedron
# ----------------------------------------------------------------------------------------------
def arcs(k):
    out = []
    for length in range(1, k):
        for start in range(k):
            out.append(frozenset((start + i) % k for i in range(length)))
    out.append(frozenset(range(k)))
    return out


def edges(k):
    return [frozenset({e, (e + 1) % k}) for e in range(k)]


def dual_constraint_rows(k):
    """One row per arc over variables (lam_0..lam_{k-1}, mu_0..mu_{k-1}): coefficient 1 on lam_e if the
    arc meets e, 1 on mu_e if the arc meets e in exactly one vertex.  Dual constraint: row . x >= 1."""
    A, E = arcs(k), edges(k)
    rows = []
    for a in A:
        row = [0] * (2 * k)
        for e, ed in enumerate(E):
            m = len(a & ed)
            if m >= 1:
                row[e] = 1
            if m == 1:
                row[k + e] = 1
        rows.append(row)
    return A, E, rows


def solve_square(M, b):
    n = len(M)
    M = [[F(v) for v in row] + [F(b[i])] for i, row in enumerate(M)]
    for col in range(n):
        piv = None
        for r in range(col, n):
            if M[r][col] != 0:
                piv = r
                break
        if piv is None:
            return None
        M[col], M[piv] = M[piv], M[col]
        inv = 1 / M[col][col]
        M[col] = [v * inv for v in M[col]]
        for r in range(n):
            if r != col and M[r][col] != 0:
                f = M[r][col]
                M[r] = [a - f * c for a, c in zip(M[r], M[col])]
    return [M[i][n] for i in range(n)]


def dual_vertices(k):
    """All vertices of {x >= 0 : row . x >= 1 for every arc row}, by exhaustive basis enumeration."""
    A, E, rows = dual_constraint_rows(k)
    nvar = 2 * k
    cons = [(row, 1) for row in rows] + [([1 if j == i else 0 for j in range(nvar)], 0) for i in range(nvar)]
    verts = set()
    for subset in itertools.combinations(range(len(cons)), nvar):
        M = [cons[i][0] for i in subset]
        b = [cons[i][1] for i in subset]
        x = solve_square(M, b)
        if x is None:
            continue
        if all(sum(c * v for c, v in zip(row, x)) >= rhs for row, rhs in cons):
            verts.add(tuple(x))
    return A, E, rows, sorted(verts)


def dominated_by(x, y, k):
    """x >= y as monomials for all 1 <= s_e <= r_e (log scale: rho_e >= sigma_e >= 0), x != y.
    Sufficient and necessary: the cone {rho >= varsigma >= 0} is generated by the rays
    (rho_e = 1, varsigma_e = 0) and (rho_e = 1, varsigma_e = 1); x - y is nonnegative on the cone iff
    it is nonnegative on all generators: lam_x[e] >= lam_y[e] and lam_x[e] + mu_x[e] >= lam_y[e] + mu_y[e]."""
    if x == y:
        return False
    return all(x[e] >= y[e] and x[e] + x[k + e] >= y[e] + y[k + e] for e in range(k))


def mono_str(x, k, names=None):
    names = names or NAMES
    parts = []
    for e in range(k):
        if x[e]:
            parts.append(f"r_{names[e]}^{x[e]}" if x[e] != 1 else f"r_{names[e]}")
    for e in range(k):
        if x[k + e]:
            parts.append(f"s_{names[e]}^{x[k + e]}" if x[k + e] != 1 else f"s_{names[e]}")
    return " ".join(parts) if parts else "1"


# D4 action on exponent vectors (k = 4): rotation e -> e+1, reflection e -> 3 - e (transpose relabelling)
def d4_images(x):
    k = 4
    lam, mu = list(x[:4]), list(x[4:])
    imgs = set()
    for refl in (False, True):
        l2, m2 = (lam[::-1], mu[::-1]) if refl else (lam, mu)
        for rot in range(4):
            l3 = [l2[(e - rot) % 4] for e in range(4)]
            m3 = [m2[(e - rot) % 4] for e in range(4)]
            imgs.add(tuple(l3 + m3))
    return imgs


def classify(x):
    """Orbit name for a k=4 dual vertex by its exponent pattern (the solver's A..H labelling)."""
    lam, mu = x[:4], x[4:]
    lsupp = [e for e in range(4) if lam[e]]
    msupp = [e for e in range(4) if mu[e]]
    opp = lambda a, b: (a - b) % 4 == 2
    one = F(1)
    half = F(1, 2)
    third = F(1, 3)
    if sorted(lam) == [0, 0, 0, one] and sorted(mu) == [0, 0, one, one]:
        i = lsupp[0]
        j, kk = msupp
        both_adjacent = (not opp(i, j)) and (not opp(i, kk))
        return "A4" if both_adjacent else "A8"
    if sorted(lam) == [0, 0, 0, one] and sorted(mu) == [0, half, half, half]:
        return "B"
    if sorted(lam) == [0, 0, half, half] and sorted(mu) == [0, 0, half, half]:
        return "C" if opp(*lsupp) else "C'"
    if sorted(lam) == [0, 0, one, one] and sorted(mu) == [0, 0, 0, 0]:
        return "D"
    if sorted(lam) == [0, 0, half, half] and sorted(mu) == [0, half, half, half]:
        return "E"
    if sorted(lam) == [0, 0, third, 2 * third] and sorted(mu) == [0, third, third, third]:
        return "F"
    if sorted(lam) == [0, third, third, third] and sorted(mu) == [0, third, third, third]:
        return "G"
    if sorted(lam) == [0, 0, half, half] and sorted(mu) == [F(1, 4)] * 4:
        return "H"
    return "other"


