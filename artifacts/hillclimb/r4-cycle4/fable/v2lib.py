def kron(A, B):
    n, m = len(A), len(A[0])
    p, q = len(B), len(B[0])
    out = [[0] * (m * q) for _ in range(n * p)]
    for i in range(n):
        for j in range(m):
            if A[i][j]:
                for a in range(p):
                    for b in range(q):
                        if B[a][b]:
                            out[i * p + a][j * q + b] = 1
    return out


def ones(n, m):
    return [[1] * m for _ in range(n)]


def eye(n):
    return [[1 if i == j else 0 for j in range(n)] for i in range(n)]


def arc_instance(mult, k=4):
    """mult: dict arc(frozenset) -> multiplicity (int >= 1).  Vertex v index set = prod_{A ∋ v} [n_A] in a fixed
    arc order; edge (v, v') relates (i, i') iff i_A = i'_A for every arc A ⊇ {v, v'}, other coordinates free."""
    E = [(e, (e + 1) % k) for e in range(k)]
    order = arcs(k)
    mats = []
    for (u, v) in E:
        M = [[1]]
        for a in order:
            n = mult.get(a, 1)
            if n <= 1:
                continue
            inu, inv = u in a, v in a
            if inu and inv:
                M = kron(M, eye(n))
            elif inu:
                M = kron(M, ones(n, 1))
            elif inv:
                M = kron(M, ones(1, n))
        mats.append(M)
    return tuple(mats)


def arc_predicted(mult, k=4):
    """(sizes, sigma2, out) predicted by the closed forms."""
    E = edges(k)
    r, s = [], []
    for e in range(k):
        pr, ps = 1, 1
        for a, n in mult.items():
            m = len(a & E[e])
            if m >= 1:
                pr *= n
            if m == 1:
                ps *= n
        r.append(pr)
        s.append(ps)
    out = 1
    for n in mult.values():
        out *= n
    return r, s, out


def perron_rowsum_check(A, p):
    """Exact certificate that ||A||_2^2 == p for a 0/1 matrix A whose Gram matrix has constant row sums p:
    a nonnegative matrix with all row sums equal to p has spectral radius exactly p."""
    G = gram_small(A)
    return all(sum(row) == p for row in G)


def integer_kth_root_floor(N, q):
    """floor(N^(1/q)) for integers N >= 0, q >= 1 (exact)."""
    if N < 2:
        return N
    lo, hi = 1, 1 << ((N.bit_length() + q - 1) // q + 1)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** q <= N:
            lo = mid
        else:
            hi = mid - 1
    return lo


def floor_pow2_frac(nu):
    """floor(2^nu) for a nonnegative Fraction nu, exactly."""
    p, q = nu.numerator, nu.denominator
    return integer_kth_root_floor(2 ** p, q)
