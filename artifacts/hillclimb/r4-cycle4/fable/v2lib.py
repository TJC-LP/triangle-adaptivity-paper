# exact simplex: max c.x  s.t.  A x <= b, x >= 0, with b >= 0 (origin feasible).  Bland's rule.
# ----------------------------------------------------------------------------------------------
def simplex_max(c, A, b):
    m, n = len(A), len(c)
    T = [[F(v) for v in A[i]] + [F(1 if i == j else 0) for j in range(m)] + [F(b[i])] for i in range(m)]
    assert all(row[-1] >= 0 for row in T)
    z = [-F(v) for v in c] + [F(0)] * m + [F(0)]
    basis = [n + i for i in range(m)]
    it = 0
    while True:
        it += 1
        assert it < 100000
        enter = None
        for j in range(n + m):
            if z[j] < 0:
                enter = j
                break
        if enter is None:
            break
        best = None
        for i in range(m):
            if T[i][enter] > 0:
                ratio = T[i][-1] / T[i][enter]
                if best is None or ratio < best[0] or (ratio == best[0] and basis[i] < basis[best[1]]):
                    best = (ratio, i)
        if best is None:
            raise ValueError("unbounded")
        i = best[1]
        piv = T[i][enter]
        T[i] = [v / piv for v in T[i]]
        for r in range(m):
            if r != i and T[r][enter] != 0:
                f = T[r][enter]
                T[r] = [a - f * bb for a, bb in zip(T[r], T[i])]
        if z[enter] != 0:
            f = z[enter]
            z = [a - f * bb for a, bb in zip(z, T[i])]
        basis[i] = enter
    x = [F(0)] * (n + m)
    for i, bi in enumerate(basis):
        x[bi] = T[i][-1]
    return x[:n], z[-1]


def arc_lp(k, rho, vs):
    """max sum nu_A  s.t.  sum_{A meets e} nu_A <= rho_e,  sum_{|A cap e| = 1} nu_A <= vs_e,  nu >= 0.
    rho, vs: lists of Fractions (logs of r_e, s_e in any base).  Returns (nu list, value)."""
    A, E = arcs(k), edges(k)
    rowsA, b = [], []
    for e in range(k):
        rowsA.append([1 if len(a & E[e]) >= 1 else 0 for a in A])
        b.append(rho[e])
        rowsA.append([1 if len(a & E[e]) == 1 else 0 for a in A])
        b.append(vs[e])
    nu, val = simplex_max([1] * len(A), rowsA, b)
    return A, nu, val


