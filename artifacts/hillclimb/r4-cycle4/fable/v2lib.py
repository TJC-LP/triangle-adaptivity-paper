def matmul(A, B):
    n, kk, m = len(A), len(B), len(B[0]) if B else 0
    out = [[0] * m for _ in range(n)]
    for i in range(n):
        Ai, oi = A[i], out[i]
        for t in range(kk):
            a = Ai[t]
            if a:
                Bt = B[t]
                for j in range(m):
                    if Bt[j]:
                        oi[j] += a * Bt[j]
    return out


def transpose(A):
    return [list(col) for col in zip(*A)] if A else []


def trace(A):
    return sum(A[i][i] for i in range(len(A)))


def out4(AR, AS, AT, AQ):
    return trace(matmul(matmul(AR, AS), matmul(AT, AQ)))


def size(A):
    return sum(map(sum, A))


def gram_small(A):
    """The smaller of A^T A and A A^T (same nonzero spectrum)."""
    if len(A) <= len(A[0]):
        return matmul(A, transpose(A))
    return matmul(transpose(A), A)


# characteristic polynomial (Faddeev-LeVerrier), coefficients c[0..n] with c[n] = 1 (monic), p(x) = sum c[i] x^i
def charpoly(M):
    n = len(M)
    I = [[F(1 if i == j else 0) for j in range(n)] for i in range(n)]
    Mk = [[F(0)] * n for _ in range(n)]
    c = [F(0)] * (n + 1)
    c[n] = F(1)
    for kk in range(1, n + 1):
        # M_k = M (M_{k-1} + c_{n-k+1} I)
        tmp = [[Mk[i][j] + (c[n - kk + 1] if i == j else 0) for j in range(n)] for i in range(n)]
        Mk = [[sum(F(M[i][t]) * tmp[t][j] for t in range(n)) for j in range(n)] for i in range(n)]
        tr = sum(Mk[i][i] for i in range(n))
        c[n - kk] = -tr / kk
    return c


def poly_eval(c, x):
    v = F(0)
    for coef in reversed(c):
        v = v * x + coef
    return v


def poly_deriv(c):
    return [c[i] * i for i in range(1, len(c))]


def poly_trim(c):
    while len(c) > 1 and c[-1] == 0:
        c = c[:-1]
    return c


def poly_rem(a, b):
    return poly_divmod(a, b)[1]


def poly_divmod(a, b):
    """quotient, remainder of a / b (Fractions)."""
    a = poly_trim([F(v) for v in a])
    b = poly_trim([F(v) for v in b])
    if len(b) == 1 and b[0] == 0:
        raise ZeroDivisionError
    q = [F(0)] * max(1, len(a) - len(b) + 1)
    while len(a) >= len(b) and not (len(a) == 1 and a[0] == 0):
        f = a[-1] / b[-1]
        shift = len(a) - len(b)
        q[shift] = f
        for i in range(len(b)):
            a[shift + i] -= f * b[i]
        a = poly_trim(a[:-1]) if len(a) > 1 else poly_trim(a)
        if len(a) < len(b):
            break
        if len(a) == len(b) and a[-1] == 0:
            a = poly_trim(a)
            if len(a) < len(b):
                break
    return poly_trim(q), poly_trim(a)


def poly_gcd(a, b):
    a = poly_trim([F(v) for v in a])
    b = poly_trim([F(v) for v in b])
    while not (len(b) == 1 and b[0] == 0):
        _, r = poly_divmod(a, b)
        a, b = b, r
    # make monic
    return [v / a[-1] for v in a]


def poly_squarefree(c):
    """c / gcd(c, c'): same distinct roots, all simple."""
    g = poly_gcd(c, poly_deriv(c))
    if len(g) == 1:
        return poly_trim([F(v) for v in c])
    q, r = poly_divmod(c, g)
    assert len(r) == 1 and r[0] == 0
    return q


def sturm_sequence(c):
    c = poly_squarefree(c)
    seq = [poly_trim(c), poly_trim(poly_deriv(c))]
    while True:
        last = seq[-1]
        if len(last) == 1 and last[0] == 0:
            seq.pop()
            break
        if len(last) == 1:
            break
        r = poly_rem(seq[-2], seq[-1])
        if len(r) == 1 and r[0] == 0:
            break
        seq.append([-v for v in r])
    return seq


def sign_changes(seq, x):
    vals = [poly_eval(p, x) for p in seq]
    s = [v for v in vals if v != 0]
    return sum(1 for i in range(1, len(s)) if (s[i] > 0) != (s[i - 1] > 0))


def count_roots(seq, a, b):
    """number of distinct real roots in (a, b]"""
    return sign_changes(seq, a) - sign_changes(seq, b)


def lambda_max_bracket(G, bits=60):
    """G: symmetric nonnegative integer PSD matrix.  Returns (lo, hi, exact) with lambda_max in (lo, hi]
    (or lo == hi == exact value when an integer root is certified).  Width hi - lo <= rowsum/2^bits."""
    n = len(G)
    if n == 0 or all(v == 0 for row in G for v in row):
        return F(0), F(0), True
    c = charpoly(G)
    rowmax = max(sum(row) for row in G)
    seq = sturm_sequence(c)
    lo, hi = F(0), F(rowmax + 1)
    # exact integer root test first: lambda_max <= rowmax; test integers downward? rowmax could be large,
    # so bisect first then test the (at most one) integer in the final bracket.
    assert count_roots(seq, lo, hi) >= 1
    for _ in range(bits):
        mid = (lo + hi) / 2
        if count_roots(seq, mid, hi) >= 1:
            lo = mid
        else:
            hi = mid
        if hi - lo < 1:
            kk = math.floor(hi)
            if kk > lo and poly_eval(c, F(kk)) == 0:
                return F(kk), F(kk), True
    return lo, hi, False


_SIGMA_CACHE = {}


def sigma2_bracket(A, bits=60):
    key = tuple(tuple(r) for r in A)
    if key in _SIGMA_CACHE:
        return _SIGMA_CACHE[key]
    G = gram_small(A)
    res = lambda_max_bracket(G, bits)
    _SIGMA_CACHE[key] = res
    return res


def stats_brackets(mats, bits=60):
    """r (ints), s_lo, s_hi (Fractions) with s_e = min(sigma_e^2, r_e) in [s_lo, s_hi]."""
    r = [size(M) for M in mats]
    s_lo, s_hi = [], []
    for M, re in zip(mats, r):
        if re == 0:
            s_lo.append(F(0))
            s_hi.append(F(0))
            continue
        lo, hi, ex = sigma2_bracket(M, bits)
        s_lo.append(min(lo, F(re)))
        s_hi.append(min(hi, F(re)))
    return r, s_lo, s_hi


